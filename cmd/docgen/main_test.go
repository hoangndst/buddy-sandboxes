package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestGenerateCLIDocs(t *testing.T) {
	tempDir := t.TempDir()

	// Seed a stale file to verify cleanup
	staleFile := filepath.Join(tempDir, "buddy-sbx_stale_obsolete.md")
	if err := os.WriteFile(staleFile, []byte("stale content"), 0644); err != nil {
		t.Fatalf("failed to create stale file: %v", err)
	}

	// 1. Generate CLI documentation
	if err := GenerateCLIDocs(tempDir); err != nil {
		t.Fatalf("GenerateCLIDocs failed: %v", err)
	}

	// 2. Verify stale file was purged
	if _, err := os.Stat(staleFile); !os.IsNotExist(err) {
		t.Errorf("expected stale file %s to be deleted", staleFile)
	}

	// 3. Verify _index.md exists and has correct front matter
	indexPath := filepath.Join(tempDir, "_index.md")
	indexBytes, err := os.ReadFile(indexPath)
	if err != nil {
		t.Fatalf("failed to read _index.md: %v", err)
	}
	indexContent := string(indexBytes)
	if !strings.Contains(indexContent, `title: "CLI Reference"`) {
		t.Errorf("_index.md missing expected title front matter")
	}
	if !strings.Contains(indexContent, `weight: 10`) {
		t.Errorf("_index.md missing expected weight front matter")
	}

	// 4. Verify redundant root command file (buddy-sbx.md) was cleaned up in favor of canonical _index.md
	rootDocPath := filepath.Join(tempDir, "buddy-sbx.md")
	if _, err := os.Stat(rootDocPath); !os.IsNotExist(err) {
		t.Errorf("expected redundant buddy-sbx.md to be removed in favor of canonical _index.md")
	}

	// 5. Verify representative subcommand files exist and contain front matter
	expectedSubcommands := []string{
		"buddy-sbx_get.md",
		"buddy-sbx_describe.md",
		"buddy-sbx_delete.md",
		"buddy-sbx_create.md",
		"buddy-sbx_run.md",
		"buddy-sbx_exec.md",
		"buddy-sbx_logs.md",
		"buddy-sbx_attach.md",
		"buddy-sbx_port-forward.md",
		"buddy-sbx_cp.md",
		"buddy-sbx_suspend.md",
		"buddy-sbx_resume.md",
		"buddy-sbx_config.md",
		"buddy-sbx_login.md",
	}

	for _, sub := range expectedSubcommands {
		subPath := filepath.Join(tempDir, sub)
		data, err := os.ReadFile(subPath)
		if err != nil {
			t.Errorf("expected subcommand doc %s to exist: %v", sub, err)
			continue
		}
		content := string(data)
		if !strings.HasPrefix(content, "---\ntitle:") {
			t.Errorf("%s does not begin with Hugo YAML front matter", sub)
		}
		if strings.Contains(content, "Auto generated by spf13/cobra") {
			t.Errorf("%s contains auto-generated timestamp tag", sub)
		}
		// Verify SEE ALSO links to root command point to ../ instead of ../buddy-sbx/
		if strings.Contains(content, "[buddy-sbx](../buddy-sbx/)") {
			t.Errorf("%s contains link to redundant ../buddy-sbx/ instead of ../", sub)
		}
	}

	// 6. Test Determinism across repeated generations
	tempDir2 := t.TempDir()
	if err := GenerateCLIDocs(tempDir2); err != nil {
		t.Fatalf("second GenerateCLIDocs failed: %v", err)
	}

	entries1, err := os.ReadDir(tempDir)
	if err != nil {
		t.Fatalf("failed to read tempDir: %v", err)
	}
	entries2, err := os.ReadDir(tempDir2)
	if err != nil {
		t.Fatalf("failed to read tempDir2: %v", err)
	}

	if len(entries1) != len(entries2) {
		t.Fatalf("file count mismatch between repeated runs: %d vs %d", len(entries1), len(entries2))
	}

	for _, e := range entries1 {
		b1, err := os.ReadFile(filepath.Join(tempDir, e.Name()))
		if err != nil {
			t.Fatalf("failed to read %s: %v", e.Name(), err)
		}
		b2, err := os.ReadFile(filepath.Join(tempDir2, e.Name()))
		if err != nil {
			t.Fatalf("failed to read second %s: %v", e.Name(), err)
		}
		if !bytes.Equal(b1, b2) {
			t.Errorf("file %s is not deterministic across repeated generations", e.Name())
		}
	}
}
