func TestCLIExamples(t *testing.T) {
	rootCmd := sbx.NewRootCmd()

	var checkExamples func(cmd *cobra.Command)
	checkExamples = func(cmd *cobra.Command) {
		example := cmd.Example
		if example != "" {
			lines := strings.Split(example, "\n")
			for _, line := range lines {
				trimmed := strings.TrimSpace(line)
				if strings.HasPrefix(trimmed, "buddy-sbx ") {
					parts := strings.Fields(trimmed)
					targetCmd, remainingArgs, err := rootCmd.Find(parts[1:])
					if err != nil || targetCmd == nil {
						targetCmd = cmd
						remainingArgs = parts[1:]
					}

					// Verify that any flag starting with -- is valid for the target command
					for _, p := range remainingArgs {
						if p == "--" {
							break // POSIX argument separator, anything after is positional arguments
						}
						if strings.HasPrefix(p, "--") {
							flagName := strings.TrimPrefix(p, "--")
							if eqIdx := strings.IndexByte(flagName, '='); eqIdx >= 0 {
								flagName = flagName[:eqIdx]
							}
							isKnownFlag := targetCmd.Flags().Lookup(flagName) != nil ||
								targetCmd.PersistentFlags().Lookup(flagName) != nil ||
								rootCmd.PersistentFlags().Lookup(flagName) != nil
							if !isKnownFlag {
								t.Errorf("command %q example has unregistered flag %q: %s", targetCmd.CommandPath(), p, line)
							}
						}
					}
				}
			}
		}
		for _, child := range cmd.Commands() {
			checkExamples(child)
		}
	}

	checkExamples(rootCmd)
}
