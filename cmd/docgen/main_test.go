func TestGenerateCLIDocs(t *testing.T) {
	tempDir, err := os.MkdirTemp("", "docgen-test-*")
	if err != nil {
		t.Fatalf("failed to create temp dir: %v", err)
	}
	defer func() {
		_ = os.RemoveAll(tempDir)
	}()

	if err := GenerateCLIDocs(tempDir); err != nil {
		t.Fatalf("GenerateCLIDocs failed: %v", err)
	}

	// Verify _index.md exists and contains notice, global flags, and command list
	indexPath := filepath.Join(tempDir, "_index.md")
	content, err := os.ReadFile(indexPath)
	if err != nil {
		t.Fatalf("failed to read _index.md: %v", err)
	}

	strContent := string(content)
	if !strings.Contains(strContent, "<!-- Code generated by buddy-sbx docgen. DO NOT EDIT. -->") {
		t.Errorf("_index.md missing generated notice")
	}
	hasGlobalFlags := strings.Contains(strContent, "--endpoint") &&
		strings.Contains(strContent, "--token") &&
		strings.Contains(strContent, "--config")
	if !hasGlobalFlags {
		t.Errorf("_index.md missing dynamic global flags")
	}
	if !strings.Contains(strContent, "| [`buddy-sbx get`]") {
		t.Errorf("_index.md missing get command row")
	}

	// Verify leaf page exists and has generated notice
	getDoc := filepath.Join(tempDir, "buddy-sbx_get.md")
	getDocContent, err := os.ReadFile(getDoc)
	if err != nil {
		t.Fatalf("failed to read %s: %v", getDoc, err)
	}
	if !strings.Contains(string(getDocContent), "<!-- Code generated by buddy-sbx docgen. DO NOT EDIT. -->") {
		t.Errorf("%s missing generated notice", getDoc)
	}
}

