const docGenHeader = "<!-- Code generated by buddy-sbx docgen. DO NOT EDIT. -->\n"

func main() {
	docType := flag.String("type", "cli", "Type of operation (cli, crd, all, verify-links, verify-all)")
	outDir := flag.String("out-dir", "site/content/docs/reference/cli", "Output directory for generated documentation")
	flag.StringVar(outDir, "output-dir", "site/content/docs/reference/cli", "Alias for --out-dir")
	refDir := flag.String("ref-dir", "site/content/docs/reference", "Root directory for reference documentation")
	flag.Parse()

	switch *docType {
	case "cli", "all":
		if err := GenerateCLIDocs(*outDir); err != nil {
			fmt.Fprintf(os.Stderr, "Error generating CLI docs: %v\n", err)
			os.Exit(1)
		}
		fmt.Printf("Successfully generated CLI reference documentation in %s\n", *outDir)
	case "crd":
		fmt.Fprintln(os.Stderr, "CRD documentation generation is managed via 'make generate-crd-docs'")
		os.Exit(1)
	case "verify-links":
		if err := ValidateReferenceLinks(*refDir); err != nil {
			fmt.Fprintf(os.Stderr, "Link validation failed: %v\n", err)
			os.Exit(1)
		}
		fmt.Printf("All reference documentation links and anchors validated successfully in %s\n", *refDir)
	case "verify-all":
		if err := ValidateReferenceLinks(*refDir); err != nil {
			fmt.Fprintf(os.Stderr, "Link validation failed: %v\n", err)
			os.Exit(1)
		}
		crdPath := filepath.Join(*refDir, "crd", "_index.md")
		cliPath := filepath.Join(*refDir, "cli")
		if err := VerifyCoverage(cliPath, crdPath); err != nil {
			fmt.Fprintf(os.Stderr, "Coverage validation failed: %v\n", err)
			os.Exit(1)
		}
		fmt.Println("All reference documentation verified successfully.")
	default:
		fmt.Fprintf(os.Stderr, "Unknown doc type %q; supported types: cli, all, crd, verify-links, verify-all\n", *docType)
		os.Exit(1)
	}
}

// GenerateCLIDocs generates Hugo-compatible markdown documentation for the buddy-sbx CLI.
func GenerateCLIDocs(dir string) error {
	if err := os.MkdirAll(dir, 0755); err != nil {
		return fmt.Errorf("failed to create output directory: %w", err)
	}

	// Purge stale generated command files (buddy-sbx*.md) while leaving other content intact
	entries, err := os.ReadDir(dir)
	if err != nil {
		return fmt.Errorf("failed to read output directory: %w", err)
	}
	for _, entry := range entries {
		name := entry.Name()
		if strings.HasPrefix(name, "buddy-sbx") && strings.HasSuffix(name, ".md") {
			if err := os.Remove(filepath.Join(dir, name)); err != nil {
				return fmt.Errorf("failed to remove stale doc %s: %w", name, err)
			}
		}
	}

	rootCmd := sbx.NewRootCmd()

	// Disable auto-gen timestamp tags for deterministic output
	disableAutoTags(rootCmd)

	// Index commands by their generated filename
	cmdMap := make(map[string]*cobra.Command)
	indexCommands(rootCmd, cmdMap)

	filePrepender := func(filename string) string {
		basename := filepath.Base(filename)
		cmd := cmdMap[basename]
		title := "buddy-sbx"
		linkTitle := "buddy-sbx"
		desc := ""
		slug := strings.TrimSuffix(basename, ".md")

		if cmd != nil {
			title = cmd.CommandPath()
			linkTitle = cmd.Name()
			desc = cmd.Short
		}

		return fmt.Sprintf(`%s---
title: "%s"
linkTitle: "%s"
description: "%s"
slug: "%s"
---

`, docGenHeader, escapeQuotes(title), escapeQuotes(linkTitle), escapeQuotes(desc), slug)
	}

	linkHandler := func(link string) string {
		if link == "buddy-sbx.md" {
			return "../"
		}
		target := strings.TrimSuffix(link, ".md")
		return "../" + target + "/"
	}

	if err := doc.GenMarkdownTreeCustom(rootCmd, dir, filePrepender, linkHandler); err != nil {
		return fmt.Errorf("failed to generate markdown tree: %w", err)
	}

	// Remove redundant root command file (buddy-sbx.md) in favor of the canonical section _index.md
	rootFile := filepath.Join(dir, "buddy-sbx.md")
	if err := os.Remove(rootFile); err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("failed to remove redundant root command doc: %w", err)
	}

	// Generate root section _index.md with dynamically discovered global flags
	if err := generateCLIIndex(dir, rootCmd); err != nil {
		return fmt.Errorf("failed to generate _index.md: %w", err)
	}

	return nil
}

func disableAutoTags(cmd *cobra.Command) {
	cmd.DisableAutoGenTag = true
	for _, c := range cmd.Commands() {
		disableAutoTags(c)
	}
}

func indexCommands(cmd *cobra.Command, m map[string]*cobra.Command) {
	if !cmd.IsAvailableCommand() && !cmd.HasSubCommands() {
		return
	}
	filename := strings.ReplaceAll(cmd.CommandPath(), " ", "_") + ".md"
	m[filename] = cmd
	for _, c := range cmd.Commands() {
		indexCommands(c, m)
	}
}

func escapeQuotes(s string) string {
	return strings.ReplaceAll(s, `"`, `\"`)
}

func generateCLIIndex(dir string, root *cobra.Command) error {
	var sb strings.Builder
	sb.WriteString(docGenHeader)
	sb.WriteString(`---
title: "CLI Reference"
linkTitle: "CLI"
description: "Reference documentation for the buddy-sbx command-line interface"
weight: 10
---

# CLI Reference: buddy-sbx

` + root.Long + `

## Global Flags

The following flags are available across all commands:

| Flag | Description |
| :--- | :--- |
`)

	var flagRows []string
	root.PersistentFlags().VisitAll(func(f *pflag.Flag) {
		shorthand := ""
		if f.Shorthand != "" {
			shorthand = fmt.Sprintf("`-%s`, ", f.Shorthand)
		}
		def := ""
		if f.DefValue != "" {
			def = fmt.Sprintf(" (default `%s`)", f.DefValue)
		}
		flagRows = append(flagRows, fmt.Sprintf("| %s`--%s` | %s%s |", shorthand, f.Name, f.Usage, def))
	})
	sort.Strings(flagRows)
	for _, row := range flagRows {
		sb.WriteString(row + "\n")
	}

	sb.WriteString(`
## Commands

| Command | Summary |
| :--- | :--- |
`)

	subcmds := root.Commands()
	sort.Slice(subcmds, func(i, j int) bool {
		return subcmds[i].Name() < subcmds[j].Name()
	})

	for _, c := range subcmds {
		if !c.IsAvailableCommand() || c.IsAdditionalHelpTopicCommand() {
			continue
		}
		pageName := strings.ReplaceAll(c.CommandPath(), " ", "_")
		sb.WriteString(fmt.Sprintf("| [`%s`](./%s/) | %s |\n", c.CommandPath(), pageName, c.Short))
	}

	indexPath := filepath.Join(dir, "_index.md")
	return os.WriteFile(indexPath, []byte(sb.String()), 0644)
}

// ValidateReferenceLinks recursively scans markdown files under refDir, verifying that all
// relative links, target markdown files, and heading anchors exist.
func ValidateReferenceLinks(refDir string) error {
	fileAnchors := make(map[string]map[string]bool)
	fileLinks := make(map[string][]linkEntry)

	err := filepath.Walk(refDir, func(path string, info os.FileInfo, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if info.IsDir() || !strings.HasSuffix(path, ".md") {
			return nil
		}

		anchors, links, scanErr := extractAnchorsAndLinks(path)
		if scanErr != nil {
			return fmt.Errorf("failed to scan %s: %w", path, scanErr)
		}
		fileAnchors[path] = anchors
		fileLinks[path] = links
		return nil
	})
	if err != nil {
		return err
	}

	linkRe := regexp.MustCompile(`\[([^\]]*)\]\(([^)]+)\)`)
	_ = linkRe

	var validationErrors []string

	for srcPath, links := range fileLinks {
		for _, entry := range links {
			dest := entry.Destination
			if strings.HasPrefix(dest, "http://") || strings.HasPrefix(dest, "https://") || strings.HasPrefix(dest, "mailto:") {
				if _, parseErr := url.Parse(dest); parseErr != nil {
					validationErrors = append(validationErrors,
						fmt.Sprintf("%s:%d: invalid external URL %q: %v", srcPath, entry.Line, dest, parseErr))
				}
				continue
			}

			// Intra-page anchor
			if strings.HasPrefix(dest, "#") {
				anchor := strings.ToLower(strings.TrimPrefix(dest, "#"))
				if !fileAnchors[srcPath][anchor] {
					validationErrors = append(validationErrors,
						fmt.Sprintf("%s:%d: broken anchor link %q in %s", srcPath, entry.Line, dest, srcPath))
				}
				continue
			}

			// Relative link
			destParts := strings.SplitN(dest, "#", 2)
			relPath := destParts[0]
			var anchor string
			if len(destParts) == 2 {
				anchor = strings.ToLower(destParts[1])
			}

			resolvedTarget, exists := resolveDocTarget(srcPath, relPath, fileAnchors)
			if !exists {
				validationErrors = append(validationErrors,
					fmt.Sprintf("%s:%d: broken relative link %q (target not found)", srcPath, entry.Line, dest))
				continue
			}

			if anchor != "" {
				if !fileAnchors[resolvedTarget][anchor] {
					validationErrors = append(validationErrors,
						fmt.Sprintf("%s:%d: broken anchor %q in target %s", srcPath, entry.Line, anchor, resolvedTarget))
				}
			}
		}
	}

	if len(validationErrors) > 0 {
		return fmt.Errorf("found %d broken links or anchors:\n  %s",
			len(validationErrors), strings.Join(validationErrors, "\n  "))
	}

	return nil
}

type linkEntry struct {
	Destination string
	Line        int
}

func extractAnchorsAndLinks(filePath string) (map[string]bool, []linkEntry, error) {
	file, err := os.Open(filePath)
	if err != nil {
		return nil, nil, err
	}
	defer func() {
		_ = file.Close()
	}()

	anchors := make(map[string]bool)
	var links []linkEntry

	scanner := bufio.NewScanner(file)
	lineNum := 0
	headingRe := regexp.MustCompile(`^(#{1,6})\s+(.+)$`)
	linkRe := regexp.MustCompile(`\[([^\]]*)\]\(([^)]+)\)`)
	htmlAnchorRe := regexp.MustCompile(`<(?:a|span)[^>]+(?:id|name)=["']([^"']+)["']`)
	inlineCodeRe := regexp.MustCompile("`[^`]+`")

	for scanner.Scan() {
		lineNum++
		line := scanner.Text()

		// Match HTML anchors
		for _, m := range htmlAnchorRe.FindAllStringSubmatch(line, -1) {
			anchors[strings.ToLower(m[1])] = true
		}

		// Match Markdown headings
		if m := headingRe.FindStringSubmatch(line); len(m) == 3 {
			headingText := strings.TrimSpace(m[2])
			slug := headingToAnchor(headingText)
			anchors[slug] = true
			anchors[strings.ToLower(headingText)] = true
			anchors[toCleanSlug(headingText)] = true
		}

		// Strip inline code blocks before scanning for markdown links to avoid false positives in regexes
		lineWithoutCode := inlineCodeRe.ReplaceAllString(line, "")

		// Match Markdown links
		for _, m := range linkRe.FindAllStringSubmatch(lineWithoutCode, -1) {
			dest := strings.TrimSpace(m[2])
			// Ignore optional link title (e.g., [text](url "title"))
			if fields := strings.Fields(dest); len(fields) > 0 {
				dest = fields[0]
			}
			links = append(links, linkEntry{
				Destination: dest,
				Line:        lineNum,
			})
		}
	}

	return anchors, links, scanner.Err()
}

func headingToAnchor(heading string) string {
	heading = strings.ToLower(heading)
	var sb strings.Builder
	for _, r := range heading {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') {
			sb.WriteRune(r)
		} else if r == ' ' || r == '-' {
			sb.WriteRune('-')
		}
	}
	res := sb.String()
	for strings.Contains(res, "--") {
		res = strings.ReplaceAll(res, "--", "-")
	}
	return strings.Trim(res, "-")
}

func toCleanSlug(s string) string {
	var sb strings.Builder
	for _, r := range strings.ToLower(s) {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') {
			sb.WriteRune(r)
		}
	}
	return sb.String()
}

func resolveDocTarget(srcPath, relLink string, existingFiles map[string]map[string]bool) (string, bool) {
	dir := filepath.Dir(srcPath)
	cleanRel := filepath.Clean(relLink)
	isLeafPage := !strings.HasSuffix(srcPath, "_index.md")

	// Standard candidate targets relative to file directory
	candidates := []string{
		filepath.Clean(filepath.Join(dir, cleanRel)),
		filepath.Clean(filepath.Join(dir, cleanRel, "_index.md")),
		filepath.Clean(filepath.Join(dir, cleanRel, "index.md")),
		filepath.Clean(filepath.Join(dir, cleanRel+".md")),
	}

	trimmed := strings.TrimSuffix(cleanRel, "/")
	candidates = append(candidates,
		filepath.Clean(filepath.Join(dir, trimmed+".md")),
		filepath.Clean(filepath.Join(dir, trimmed, "_index.md")),
	)

	// In Hugo, a leaf page foo.md is served as /foo/, so a link ../bar/ from foo.md
	// resolves to sibling bar.md in the same directory!
	// Similarly, ../ from foo.md resolves to _index.md in the same directory!
	if isLeafPage && strings.HasPrefix(cleanRel, "..") {
		afterDotDot := strings.TrimPrefix(cleanRel, "..")
		afterDotDot = strings.TrimPrefix(afterDotDot, "/")
		if afterDotDot == "" {
			candidates = append(candidates, filepath.Clean(filepath.Join(dir, "_index.md")))
		} else {
			trimmedSibling := strings.TrimSuffix(afterDotDot, "/")
			candidates = append(candidates,
				filepath.Clean(filepath.Join(dir, trimmedSibling+".md")),
				filepath.Clean(filepath.Join(dir, trimmedSibling, "_index.md")),
			)
		}
	}

	for _, c := range candidates {
		if _, ok := existingFiles[c]; ok {
			return c, true
		}
		if info, err := os.Stat(c); err == nil && !info.IsDir() {
			return c, true
		}
	}

	return "", false
}

// VerifyCoverage validates that all public Cobra commands and CRDs are covered in the generated documentation.
func VerifyCoverage(cliDir string, crdPath string) error {
	rootCmd := sbx.NewRootCmd()

	// Check CLI commands
	var checkCmd func(cmd *cobra.Command) error
	checkCmd = func(cmd *cobra.Command) error {
		if cmd.Hidden || (!cmd.IsAvailableCommand() && !cmd.HasSubCommands()) {
			return nil
		}
		if cmd.Parent() != nil { // Skip root command since it is documented in _index.md
			filename := strings.ReplaceAll(cmd.CommandPath(), " ", "_") + ".md"
			docPath := filepath.Join(cliDir, filename)
			if _, err := os.Stat(docPath); os.IsNotExist(err) {
				return fmt.Errorf("missing CLI documentation for command %q (expected %s)", cmd.CommandPath(), docPath)
			}
		}
		for _, child := range cmd.Commands() {
			if err := checkCmd(child); err != nil {
				return err
			}
		}
		return nil
	}

	if err := checkCmd(rootCmd); err != nil {
		return err
	}

	// Check CRD kinds
	crdContent, err := os.ReadFile(crdPath)
	if err != nil {
		return fmt.Errorf("failed to read CRD reference doc %s: %w", crdPath, err)
	}

	expectedKinds := []string{
		"Sandbox",
		"SandboxPool",
		"SandboxLease",
		"NetworkProfile",
		"Workspace",
	}

	text := string(crdContent)
	for _, kind := range expectedKinds {
		heading := "### " + kind
		if !strings.Contains(text, heading) {
			return fmt.Errorf("missing CRD documentation for kind %q in %s", kind, crdPath)
		}
	}

	return nil
}
